/*
 * USER_Motor_Driver.c
 *
 *  Note on clocks (SystemClock_Config): SYSCLK 72 MHz, APB1 /8, APB2 /16.
 *  Timer kernel clock = 2 x PCLK when the APB prescaler is not 1, so
 *  TIM2/TIM3 run at 18 MHz and TIM1 at 9 MHz. The old code assumed 9 MHz for
 *  all timers, which is why "50 Hz" really was 100 Hz on motors 1/3/4.
 *  Here the prescaler is computed at run time from the real clock.
 */
/*
 * ============================================================================
 *  OVERVIEW - pulse output driver for the 4 ESCs (brushless motor controllers)
 * ============================================================================
 *  1. What does this module do?
 *     - A SimonK ESC does not take a "throttle percentage". It takes a HIGH
 *       PULSE whose width is 1000..2000 us, repeated continuously (the same
 *       kind of signal as an RC servo):
 *           1000 us = stop (zero throttle), 2000 us = full throttle.
 *     - This module turns "a number of us" into a real PWM pulse on 4 timer
 *       pins. The rest of the firmware only works in us and never needs to
 *       know which timer or which prescaler is used.
 *
 *  2. Hardware
 *       M1 front-left  : TIM3 CH1 (PB4)
 *       M2 back-left   : TIM1 CH1 (PA8)
 *       M3 front-right : TIM3 CH3 (PB0)
 *       M4 back-right  : TIM2 CH3 (PB10)
 *     The BLDCx_VCC / BLDCx_GND pins are plain GPIOs held at 1 / 0 to act as
 *     a "reference supply" for the signal wires, matching the original
 *     wiring (see Motor_PowerPins).
 *
 *  3. Why is the prescaler computed at run time?
 *     - Clocks: SYSCLK 72 MHz, APB1 /8 -> PCLK1 = 9 MHz,
 *                              APB2 /16 -> PCLK2 = 4.5 MHz.
 *     - STM32 rule: if the APB divider is not 1, the clock fed to the timer
 *       is 2 x PCLK. Therefore:
 *           TIM2, TIM3 (on APB1): 2 x 9   = 18 MHz
 *           TIM1       (on APB2): 2 x 4.5 =  9 MHz
 *     - The old code assumed every timer ran at 9 MHz -> TIM2/TIM3 counted
 *       twice as fast, "50 Hz" really was 100 Hz and the pulse widths were
 *       also wrong by a factor of 2 -> motor 2 (TIM1) behaved differently
 *       from the other three.
 *     - This version asks the HAL for the real clock and computes the
 *       values itself, so all motors stay correct even if the clock tree is
 *       changed later.
 *
 *  4. Timer setup
 *     - 1 tick = 1 us (1 MHz counter) -> the CCR (compare) value IS the pulse
 *       width in us. Example: CCR = 1500 -> 1500 us high pulse.
 *     - Period 400 Hz -> 2500 us -> ARR = 2500 - 1 = 2499.
 *       The longest pulse (2000 us) < 2500 us, so there is always a low gap
 *       between two pulses.
 *
 *  5. Who calls it?
 *     - Motor_Init(): called once at start-up (USER_System.c), BEFORE the
 *       FreeRTOS scheduler starts, because it blocks (HAL_Delay) 3 s so the
 *       ESCs can arm.
 *     - Motor_WriteAllUs()/Motor_StopAll(): called from BLDCTask every
 *       control cycle (250 Hz) after the mixer has run.
 *     - Motor_GetUs(): the UI / telemetry read back the current output.
 *
 *  6. Data flow
 *       PID -> Mixer (us for 4 motors) -> Motor_WriteAllUs -> clamp 1000..2000
 *           -> write CCR -> timer generates the pulse -> ESC -> motor.
 *     The CCR preload is enabled (HAL_TIM_PWM_ConfigChannel sets OCxPE), so
 *     a new CCR value takes effect at the next PWM period and never
 *     distorts the pulse currently being output.
 * ============================================================================
 */
#include "USER_Motor_Driver.h"
#include "USER_Config.h"
#include "main.h"

typedef struct
{
    TIM_HandleTypeDef *htim;
    uint32_t           channel;
} MotorOut_TypeDef;

/* Motor -> (timer, channel) table. Array index 0..3 = M1..M4.
 * htim1/2/3 are the handles generated by CubeMX in main.c. */
static const MotorOut_TypeDef s_motor[MOTOR_COUNT] =
{
    { &htim3, TIM_CHANNEL_1 },   /* M1 front left  */
    { &htim1, TIM_CHANNEL_1 },   /* M2 back left   */
    { &htim3, TIM_CHANNEL_3 },   /* M3 front right */
    { &htim2, TIM_CHANNEL_3 },   /* M4 back right  */
};

/* Copy of the pulse (us) currently output on each motor, so Motor_GetUs can
 * return it without reading CCR. volatile because other tasks (UI) read it. */
static volatile uint16_t s_motor_us[MOTOR_COUNT];

/* Timer kernel clock in Hz */
/* Returns the real clock (Hz) that drives the counter of timer `inst`.
 * - TIM1/8/9/10/11 sit on APB2, all other timers on APB1.
 * - If the APB divider is 1 (PPRE bits = 0) the timer clock = PCLK,
 *   otherwise timer clock = 2 x PCLK (STM32F4 hardware rule).
 * Example with the current setup: TIM3 -> PCLK1 9 MHz, PPRE1 != 0 -> 18 MHz;
 *                                 TIM1 -> PCLK2 4.5 MHz, PPRE2 != 0 -> 9 MHz. */
static uint32_t Motor_TimerClock(TIM_TypeDef *inst)
{
    uint32_t pclk;
    uint32_t apb_div_bits;

    if ((inst == TIM1) || (inst == TIM8) || (inst == TIM9) ||
        (inst == TIM10) || (inst == TIM11))
    {
        pclk = HAL_RCC_GetPCLK2Freq();
        apb_div_bits = RCC->CFGR & RCC_CFGR_PPRE2;
    }
    else
    {
        pclk = HAL_RCC_GetPCLK1Freq();
        apb_div_bits = RCC->CFGR & RCC_CFGR_PPRE1;
    }

    return (apb_div_bits == 0U) ? pclk : (2U * pclk);
}

/* 1 MHz counter, period = 1 / MOTOR_PWM_FREQ_HZ */
/* Re-programs the prescaler (PSC) and period (ARR) of a timer that CubeMX
 * has already initialised, so that 1 tick = 1 us and the PWM frequency =
 * MOTOR_PWM_FREQ_HZ (400 Hz). The timer is left disabled here;
 * HAL_TIM_PWM_Start in Motor_Init enables it again. */
static void Motor_ConfigTimer(TIM_HandleTypeDef *htim)
{
    /* The counter runs at clock / (PSC + 1). For 1 MHz:
     *   TIM2/TIM3: PSC = 18 MHz / 1 MHz - 1 = 17
     *   TIM1     : PSC =  9 MHz / 1 MHz - 1 =  8 */
    uint32_t psc = (Motor_TimerClock(htim->Instance) / 1000000U) - 1U;
    /* PWM period = (ARR + 1) ticks. 400 Hz -> 1e6 / 400 - 1 = 2499 (2.5 ms). */
    uint32_t arr = (1000000U / MOTOR_PWM_FREQ_HZ) - 1U;

    __HAL_TIM_DISABLE(htim);
    /* Update the Init struct too (so a later HAL re-init keeps the right
     * values) and write PSC/ARR directly into the registers. */
    htim->Init.Prescaler = psc;
    htim->Init.Period = arr;
    __HAL_TIM_SET_PRESCALER(htim, psc);
    __HAL_TIM_SET_AUTORELOAD(htim, arr);
    __HAL_TIM_SET_COUNTER(htim, 0);
    htim->Instance->EGR = TIM_EGR_UG;   /* load PSC/ARR now */
    /* PSC is a buffered register: a new value is only loaded on an update
     * event. Setting UG generates an update event in software to load it
     * immediately. */
}

/* Drives the "reference VCC/GND" pins of the ESC signal wires to fixed
 * levels (old wiring): VCC pins = 1, GND pins = 0. */
/*
 * The old "BLDCx_VCC" pins (PG15, PC8, PC4, PE14) were driven HIGH. If the
 * ESC red wire (+5 V produced by the ESC's BEC once the battery is plugged
 * in) is connected to such a pin, 5 V fights the 3.3 V output -> current into
 * the MCU supply -> brown-out reset. An ESC only needs SIGNAL + GND, so these
 * pins are now released: input, no pull = high impedance (they neither drive
 * nor short the 5 V). CubeMX configures them as output LOW in MX_GPIO_Init(),
 * which would SHORT a present 5 V to ground, so this runs right after the
 * CubeMX init (main.c USER CODE 2), before the 3 s ESC arming delay.
 * Set MOTOR_ESC_VCC_PINS_HIGH = 1 in USER_Config.h for the old behaviour.
 * PC4 is never touched in the GAMEPAD build (USB VBUS power switch).
 */
/* ESC plug reference pins, from USER_Config.h (ESCx_GND_* / ESCx_VCC_*) */
typedef struct
{
    GPIO_TypeDef *gnd_port;
    uint16_t      gnd_pin;
    GPIO_TypeDef *vcc_port;
    uint16_t      vcc_pin;
} EscRefPins;

static const EscRefPins s_esc_ref[MOTOR_COUNT] =
{
    { ESC1_GND_PORT, ESC1_GND_PIN, ESC1_VCC_PORT, ESC1_VCC_PIN },
    { ESC2_GND_PORT, ESC2_GND_PIN, ESC2_VCC_PORT, ESC2_VCC_PIN },
    { ESC3_GND_PORT, ESC3_GND_PIN, ESC3_VCC_PORT, ESC3_VCC_PIN },
    { ESC4_GND_PORT, ESC4_GND_PIN, ESC4_VCC_PORT, ESC4_VCC_PIN },
};

static void Motor_GpioClocks(void)
{
    __HAL_RCC_GPIOA_CLK_ENABLE();
    __HAL_RCC_GPIOB_CLK_ENABLE();
    __HAL_RCC_GPIOC_CLK_ENABLE();
    __HAL_RCC_GPIOE_CLK_ENABLE();
    __HAL_RCC_GPIOF_CLK_ENABLE();
    __HAL_RCC_GPIOG_CLK_ENABLE();
}

void Motor_ReleaseVccPins(void)
{
#if (MOTOR_ESC_VCC_PINS_HIGH == 0)
    GPIO_InitTypeDef gpio = {0};
    uint8_t i;

    Motor_GpioClocks();
    gpio.Mode = GPIO_MODE_INPUT;
    gpio.Pull = GPIO_NOPULL;
    for (i = 0; i < MOTOR_COUNT; i++)
    {
        gpio.Pin = s_esc_ref[i].vcc_pin;
        HAL_GPIO_Init(s_esc_ref[i].vcc_port, &gpio);
    }
#if (FC_VARIANT != FC_VARIANT_GAMEPAD)
    /* Old M3 "VCC" pin, no longer used by the plug: release it too.
     * (In the GAMEPAD build PC4 belongs to the USB power switch.) */
    gpio.Pin = BLDC3_VCC_PC4_Pin;
    HAL_GPIO_Init(BLDC3_VCC_PC4_GPIO_Port, &gpio);
#endif
#endif
}

static void Motor_PowerPins(void)
{
    GPIO_InitTypeDef gpio = {0};
    uint8_t i;

    Motor_GpioClocks();

    /* Signal reference (GND) pins: output LOW. Configured here explicitly
     * because some of them (e.g. PF11 for M3) are not set up by CubeMX. */
    gpio.Mode = GPIO_MODE_OUTPUT_PP;
    gpio.Pull = GPIO_NOPULL;
    gpio.Speed = GPIO_SPEED_FREQ_LOW;
    for (i = 0; i < MOTOR_COUNT; i++)
    {
        HAL_GPIO_WritePin(s_esc_ref[i].gnd_port, s_esc_ref[i].gnd_pin, GPIO_PIN_RESET);
        gpio.Pin = s_esc_ref[i].gnd_pin;
        HAL_GPIO_Init(s_esc_ref[i].gnd_port, &gpio);
    }

#if (MOTOR_ESC_VCC_PINS_HIGH == 1)
    /* Old behaviour: "VCC" pins driven HIGH. NEVER connect the ESC +5 V wire. */
    gpio.Mode = GPIO_MODE_OUTPUT_PP;
    for (i = 0; i < MOTOR_COUNT; i++)
    {
        HAL_GPIO_WritePin(s_esc_ref[i].vcc_port, s_esc_ref[i].vcc_pin, GPIO_PIN_SET);
        gpio.Pin = s_esc_ref[i].vcc_pin;
        HAL_GPIO_Init(s_esc_ref[i].vcc_port, &gpio);
    }
#else
    Motor_ReleaseVccPins();         /* again, in case something reconfigured them */
#endif
}

/* Initialises all motor outputs:
 *   1) set the reference pins, 2) configure the 3 timers (1 us/tick, 400 Hz),
 *   3) output the 1000 us STOP pulse on all 4 channels and start PWM,
 *   4) wait MOTOR_ESC_ARM_DELAY_MS (3 s) so the ESCs see "throttle = 0" and arm.
 * BLOCKS for 3 s with HAL_Delay -> must be called before the scheduler runs. */
void Motor_Init(void)
{
    uint8_t i;

    Motor_PowerPins();

    Motor_ConfigTimer(&htim1);
    Motor_ConfigTimer(&htim2);
    Motor_ConfigTimer(&htim3);

    for (i = 0; i < MOTOR_COUNT; i++)
    {
        s_motor_us[i] = MOTOR_STOP_US;
        __HAL_TIM_SET_COMPARE(s_motor[i].htim, s_motor[i].channel, MOTOR_STOP_US);
        HAL_TIM_PWM_Start(s_motor[i].htim, s_motor[i].channel);
    }

    /* ESCs need a steady zero-throttle signal to arm */
    HAL_Delay(MOTOR_ESC_ARM_DELAY_MS);
}

/* Sets the pulse width of one motor.
 *   motor    : 1..4 (numbered as on the frame, NOT 0..3)
 *   pulse_us : wanted pulse width in us; clamped to [1000, 2000]
 * Returns false for an invalid motor number. Because the timer counts
 * 1 us per tick, pulse_us is written to CCR directly, no conversion. */
bool Motor_WriteUs(uint8_t motor, uint16_t pulse_us)
{
    if ((motor < 1U) || (motor > MOTOR_COUNT))
        return false;

    if (pulse_us < MOTOR_STOP_US)
        pulse_us = MOTOR_STOP_US;
    if (pulse_us > MOTOR_MAX_US)
        pulse_us = MOTOR_MAX_US;

    s_motor_us[motor - 1U] = pulse_us;
    __HAL_TIM_SET_COMPARE(s_motor[motor - 1U].htim, s_motor[motor - 1U].channel, pulse_us);
    return true;
}

/* Writes all 4 motors at once (pulse_us[0..3] = M1..M4). Called from BLDCTask. */
void Motor_WriteAllUs(const uint16_t pulse_us[MOTOR_COUNT])
{
    uint8_t i;

    for (i = 0; i < MOTOR_COUNT; i++)
        Motor_WriteUs(i + 1U, pulse_us[i]);
}

/* Puts all 4 motors back to the STOP pulse (1000 us) - used on disarm / failsafe. */
void Motor_StopAll(void)
{
    uint8_t i;

    for (i = 0; i < MOTOR_COUNT; i++)
        Motor_WriteUs(i + 1U, MOTOR_STOP_US);
}

uint16_t Motor_GetUs(uint8_t motor)
{
    if ((motor < 1U) || (motor > MOTOR_COUNT))
        return 0;
    return s_motor_us[motor - 1U];
}
