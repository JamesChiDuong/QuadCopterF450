"""Generate QuadShield.kicad_sch from design.py using the KiCad 8 libraries.

Every connected pin gets a short wire stub and a net label (same label text
= same net), unused pins get a no-connect flag, power nets get a PWR_FLAG.
Run:  python gen_sch.py   (any Python 3; only reads the KiCad .kicad_sym)
"""
import math
import os
import uuid

import design
from sexpr import Sym, dump, find, find_all, parse

KICAD = os.environ.get("KICAD_SHARE", "C:/Users/Lenovo/AppData/Local/Programs/KiCad/8.0/share/kicad")
PROJECT = "QuadShield"
NS = uuid.UUID("6f1d3c2a-6c1e-4f5e-9a51-0b7f0d2a9e11")
ROOT_UUID = str(uuid.uuid5(NS, "root"))
GRID = 2.54


def uid(*parts):
    return str(uuid.uuid5(NS, "/".join(str(p) for p in parts)))


_lib_cache = {}


def lib_symbols(lib):
    if lib not in _lib_cache:
        path = f"{KICAD}/symbols/{lib}.kicad_sym"
        _lib_cache[lib] = {s[1]: s for s in find_all(parse(open(path, encoding="utf-8").read()), "symbol")}
    return _lib_cache[lib]


def load_symbol(lib_id):
    """Return a flattened copy of the library symbol, renamed to lib_id."""
    lib, name = lib_id.split(":")
    syms = lib_symbols(lib)
    s = syms[name]
    ext = find(s, "extends")
    if ext:
        parent = load_symbol(f"{lib}:{ext[1]}")
        base_name = ext[1]
        out = [Sym("symbol"), lib_id]
        props = {p[1]: p for p in find_all(s, "property")}
        for e in parent[2:]:
            if isinstance(e, list) and e and e[0] == "property" and e[1] in props:
                out.append(props.pop(e[1]))
            elif isinstance(e, list) and e and e[0] == "symbol":
                sub = list(e)
                sub[1] = sub[1].replace(base_name, name, 1)
                out.append(sub)
            else:
                out.append(e)
        out.extend(props.values())
        return out
    out = [Sym("symbol"), lib_id] + [e for e in s[2:]]
    return out


def symbol_pins(sym):
    """{number: (x, y, angle, type)} of unit 1 / body style 1 (symbol coords, y up)."""
    pins = {}
    name = sym[1].split(":")[1]
    for sub in find_all(sym, "symbol"):
        parts = sub[1].rsplit("_", 2)
        if len(parts) == 3 and parts[1] not in ("0", "1"):
            continue
        if len(parts) == 3 and parts[2] not in ("0", "1"):
            continue
        for p in find_all(sub, "pin"):
            at = find(p, "at")
            num = find(p, "number")[1]
            pins[num] = (float(at[1]), float(at[2]), float(at[3]) if len(at) > 3 else 0.0, str(p[1]))
    return pins


def effects(size=1.27, hide=False, justify=None):
    e = [Sym("effects"), [Sym("font"), [Sym("size"), size, size]]]
    if justify:
        e.append([Sym("justify")] + [Sym(j) for j in justify])
    if hide:
        e.append([Sym("hide"), Sym("yes")])
    return e


def prop(name, value, x, y, hide=False):
    return [Sym("property"), name, value, [Sym("at"), x, y, 0], effects(hide=hide)]


def snap(v):
    return round(v / 1.27) * 1.27


def main():
    sch = [Sym("kicad_sch"), [Sym("version"), Sym("20231120")], [Sym("generator"), "eeschema"],
           [Sym("generator_version"), "8.0"], [Sym("uuid"), ROOT_UUID], [Sym("paper"), "A2"],
           [Sym("title_block"), [Sym("title"), "QuadShield - DISC1 carrier for QuadCopter F450"],
            [Sym("date"), "2026-11-24"], [Sym("rev"), "A"],
            [Sym("comment"), 1, "Generated by gen_sch.py from design.py - edit design.py, not this file"],
            [Sym("comment"), 2, "Pinout: UM1670 table 7; buck: Diodes DS41326 fig.1"]]]
    libs = {}
    body = []

    parts = list(design.PARTS.items())
    # PWR_FLAGs on nets that have power inputs / are supplied from connectors
    flags = ["GND", "VBAT_RAW", "VBAT", "+5V", "+5V_BUCK", "+3V3"]

    # Layout: J1, J2 tall columns on the left, the rest in a grid
    col_x = 40.64
    positions = {}
    x, y, col_w = 200.66, 40.64, 76.2
    for ref, data in parts:
        if ref == "J1":
            positions[ref] = (40.64, 60.96)
        elif ref == "J2":
            positions[ref] = (124.46, 60.96)
        else:
            positions[ref] = (x, y)
            y += 35.56
            if y > 380:
                y = 40.64
                x += col_w

    for ref, (value, lib_id, fp, pinmap, lcsc, note) in parts:
        if lib_id not in libs:
            libs[lib_id] = load_symbol(lib_id)
        sym = libs[lib_id]
        pins = symbol_pins(sym)
        X, Y = positions[ref]
        su = uid("sym", ref)
        inst = [Sym("symbol"), [Sym("lib_id"), lib_id], [Sym("at"), X, Y, 0], [Sym("unit"), 1],
                [Sym("exclude_from_sim"), Sym("no")], [Sym("in_bom"), Sym("yes")],
                [Sym("on_board"), Sym("yes")], [Sym("dnp"), Sym("yes" if "DNP" in value else "no")],
                [Sym("uuid"), su],
                prop("Reference", ref, X, Y - 12.7),
                prop("Value", value, X, Y + 12.7),
                prop("Footprint", fp, X, Y, hide=True),
                prop("Datasheet", "~", X, Y, hide=True),
                prop("Description", note, X, Y, hide=True)]
        if lcsc:
            inst.append(prop("LCSC", lcsc, X, Y, hide=True))
        for num in pins:
            inst.append([Sym("pin"), num, [Sym("uuid"), uid("pin", ref, num)]])
        inst.append([Sym("instances"), [Sym("project"), PROJECT,
                     [Sym("path"), "/" + ROOT_UUID, [Sym("reference"), ref], [Sym("unit"), 1]]]])
        body.append(inst)

        for num, (px, py, ang, ptype) in pins.items():
            wx, wy = snap(X + px), snap(Y - py)
            net = pinmap.get(int(num)) if num.isdigit() else None
            if net is None:
                body.append([Sym("no_connect"), [Sym("at"), wx, wy], [Sym("uuid"), uid("nc", ref, num)]])
                continue
            # outward direction = opposite of the pin angle (symbol y up -> world y down)
            a = math.radians(ang)
            dx, dy = -math.cos(a), math.sin(a)
            ex, ey = snap(wx + dx * GRID), snap(wy + dy * GRID)
            body.append([Sym("wire"), [Sym("pts"), [Sym("xy"), wx, wy], [Sym("xy"), ex, ey]],
                         [Sym("stroke"), [Sym("width"), 0], [Sym("type"), Sym("default")]],
                         [Sym("uuid"), uid("w", ref, num)]])
            if abs(dx) > 0.5:
                lang, just = (0, ["left", "bottom"]) if dx > 0 else (180, ["right", "bottom"])
            else:
                lang, just = (270, ["right", "bottom"]) if dy > 0 else (90, ["left", "bottom"])
            body.append([Sym("label"), net, [Sym("at"), ex, ey, lang],
                         [Sym("fields_autoplaced"), Sym("yes")], effects(justify=just),
                         [Sym("uuid"), uid("lbl", ref, num)]])

    # PWR_FLAGs
    flag_id = "power:PWR_FLAG"
    libs[flag_id] = load_symbol(flag_id)
    fx, fy = 40.64, 170.18
    for i, net in enumerate(flags):
        X, Y = fx + i * 20.32, fy
        su = uid("flag", net)
        body.append([Sym("symbol"), [Sym("lib_id"), flag_id], [Sym("at"), X, Y, 0], [Sym("unit"), 1],
                     [Sym("exclude_from_sim"), Sym("no")], [Sym("in_bom"), Sym("no")],
                     [Sym("on_board"), Sym("no")], [Sym("dnp"), Sym("no")], [Sym("uuid"), su],
                     prop("Reference", f"#FLG0{i + 1}", X, Y - 3.81, hide=True),
                     prop("Value", "PWR_FLAG", X, Y - 3.81),
                     prop("Footprint", "", X, Y, hide=True),
                     prop("Datasheet", "~", X, Y, hide=True),
                     [Sym("pin"), "1", [Sym("uuid"), uid("flagpin", net)]],
                     [Sym("instances"), [Sym("project"), PROJECT,
                      [Sym("path"), "/" + ROOT_UUID, [Sym("reference"), f"#FLG0{i + 1}"], [Sym("unit"), 1]]]]])
        body.append([Sym("wire"), [Sym("pts"), [Sym("xy"), X, Y], [Sym("xy"), X, Y + 5.08]],
                     [Sym("stroke"), [Sym("width"), 0], [Sym("type"), Sym("default")]],
                     [Sym("uuid"), uid("fw", net)]])
        body.append([Sym("label"), net, [Sym("at"), X, Y + 5.08, 270],
                     [Sym("fields_autoplaced"), Sym("yes")], effects(justify=["right", "bottom"]),
                     [Sym("uuid"), uid("flbl", net)]])

    # Notes
    notes = [
        "QuadShield: plugs UNDER the STM32F429I-DISC1 (J1 = P1, J2 = P2, 2x32 female sockets).",
        "ESC headers: pin1 signal, pin2 (red BEC wire) NOT connected, pin3 GND.",
        "Power: XT30 2S-4S -> PTC -> SS34 -> AP63205 5V/2A -> SS34 OR diode -> DISC1 5V (UM1670 6.4).",
        "GPS UART5: GPS TX -> PD2 (P1-40), GPS RX <- PC12 (P1-43). Compass on I2C2 with the MPU.",
        "R6/R7 I2C pull-ups: DNP (GY-521 already has 4k7). Battery sense: PC3 = VBAT x 22/122.",
    ]
    for i, t in enumerate(notes):
        body.append([Sym("text"), t, [Sym("exclude_from_sim"), Sym("no")],
                     [Sym("at"), 40.64, 190.5 + i * 5.08, 0], effects(size=1.778, justify=["left", "bottom"]),
                     [Sym("uuid"), uid("note", i)]])

    sch.append([Sym("lib_symbols")] + list(libs.values()))
    sch.extend(body)
    sch.append([Sym("sheet_instances"), [Sym("path"), "/", [Sym("page"), "1"]]])
    open(f"{PROJECT}.kicad_sch", "w", encoding="utf-8", newline="\n").write(dump(sch) + "\n")

    if not os.path.exists(f"{PROJECT}.kicad_pro"):
        open(f"{PROJECT}.kicad_pro", "w", encoding="utf-8").write(
            '{\n  "meta": {"filename": "QuadShield.kicad_pro", "version": 1},\n'
            '  "sheets": [["' + ROOT_UUID + '", "Root"]]\n}\n')
    print("wrote", f"{PROJECT}.kicad_sch", "parts:", len(parts))


if __name__ == "__main__":
    main()
