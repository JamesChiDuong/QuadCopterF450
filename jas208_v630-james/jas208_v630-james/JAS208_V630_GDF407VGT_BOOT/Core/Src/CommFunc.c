//============================================================================//
// @brief  Set the first occurence of a character in a string to null character.
// @param  pcStr: Pointer to the string.
//         cEnd: Character to be changed. 
// @retval None.
//============================================================================//
void StopChar(char *pcStr, char cEnd)
{
	ChangeChar(pcStr, cEnd, '\0');
}

//============================================================================//
// @brief  Set the first occurence of a character in a string to 
//         another character.
// @param  pcStr: Pointer to the string.
//         cSource: Character to be changed. 
//         cTarget: Character for changing to. 
// @retval None.
//============================================================================//
void ChangeChar(char *pcStr, char cSource, char cTarget)
{
	uint8_t u8ChrCnt = 0;
	
	while(*(pcStr + u8ChrCnt))
	{
		if(*(pcStr + u8ChrCnt) == cSource)
		{
			*(pcStr + u8ChrCnt) = cTarget;
			
			return;
		}
		
		u8ChrCnt++;
	}
}

//============================================================================//
// @brief  Count the number of a character in a string.
// @param  pcStr: Pointer to the string.
//         cChar: Character to count. 
// @retval The number of character founded in format uint8_t.
//============================================================================//
uint8_t CountChar(char *pcStr, char cChar)
{
	uint8_t i = 0, CntCh = 0;
	
	
	while(*(pcStr + i))
	{
		if(*(pcStr + i) == cChar)
			CntCh++;
		
		i++;
	}
	
	return CntCh;
}

//============================================================================//
// @brief  Find the first occurrence of a character sequence in a string.
// @param  pcDat: Pointer to the string.
//         pcSeq: Pointer to the character sequence. 
//         pu16Pos: Pointer to the variable indicating the first occurence of 
//                  the character sequence. 
// @retval True: The character sequence exists in the string.
//         False: The character sequence does not exist in the string.
//============================================================================//
bool FindSequence(char *pcDat, char *pcSeq, uint16_t *pu16Pos)
{
  char *pcBuf;
	
	
	if(strlen(pcDat) < strlen(pcSeq))
		return FALSE;
	
	pcBuf = (char *)malloc(sizeof(char) * strlen(pcSeq));
	
	*pu16Pos = 0;
	
	// Compare data string at different positions to the characters sequence 
	while((*pu16Pos) != (strlen(pcDat) - strlen(pcSeq) + 1))
	{
	  memcpy(pcBuf, &(pcDat[*pu16Pos]), strlen(pcSeq));
		
		if(strncmp(pcBuf, pcSeq, strlen(pcSeq)) == 0)
    {
      free(pcBuf);
			
			pcBuf = NULL;
			
			return TRUE;
    }
		
		(*pu16Pos)++;
	}
	
	free(pcBuf);
	
	pcBuf = NULL;
	
	return FALSE;
}

