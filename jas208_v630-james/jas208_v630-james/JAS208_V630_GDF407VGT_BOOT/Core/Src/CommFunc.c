//============================================================================//
// @brief  Delay in microseconds.
// @param  u32_uSec: Number of microseconds to delay.
// @retval None.
//============================================================================//
void Delay_uS(const uint32_t u32_uSec)
{
	uint32_t u32Cnt = 0;
	const uint32_t u32Time = (120 * u32_uSec / 7);
	
	
	do
	{
	  if(++u32Cnt > u32Time)
		  return;
	}while (1);
}

//============================================================================//
// @brief  Convert a number in Binary format to BCD format.
// @param  u8BinVal: Number in Binary format.
// @retval BCD number in uint8_t format.
//============================================================================//
uint8_t Bin_2_BCD(uint8_t u8BinVal)
{
	uint8_t u8BCD_High = 0;
	
	
	while (u8BinVal >= 10) 
	{
		u8BCD_High++;
		
		u8BinVal -= 10;
	}
	
	return ((uint8_t)(u8BCD_High << 4) | u8BinVal);
}

