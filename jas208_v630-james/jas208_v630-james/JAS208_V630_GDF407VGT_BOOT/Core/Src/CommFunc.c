//============================================================================//
// @brief  Convert a number in Binary format to BCD format ver 2.
// @param  u8BinVal: Number in Binary format.
// @retval BCD number in uint8_t format.
//============================================================================//
uint8_t Bin_2_BCD2(uint8_t u8BinValue)
{
	uint8_t u8BCDHigh = 0;
	
	
	while(u8BinValue >= 10) 
	{
		u8BCDHigh++;
		
		u8BinValue -= 10;
	}
	
	return ((uint8_t)(u8BCDHigh << 4) | u8BinValue);
}

